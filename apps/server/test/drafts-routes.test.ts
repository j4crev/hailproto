import {expect,it,vi} from 'vitest';
import {createApp} from '../src/app.js';
import type {AppConfig} from '../src/config.js';
import type {AccountApiRepository} from '../src/accounts/repository.js';
import type {AccountMessaging} from '../src/accounts/messaging.js';
import type {GrantRepository} from '../src/grants/repository.js';
import type {GrantService} from '../src/grants/service.js';
it('guards draft reads and writes with account scopes, passkeys, CSRF and migration policy',async()=>{
  const session={account_id:crypto.randomUUID(),did:'did:plc:'+'a'.repeat(24),credential_id:crypto.randomUUID(),serving_generation:1,passkey_credential_id:'key' as string|null,scopes:['messages:read','messages:write'],migration_state:null as string|null};
  let authenticated=true;
  const read=vi.fn(async()=>null),mutate=vi.fn(async()=>({revision:1}));
  const origin='https://example.com',app=createApp({publicOrigin:origin,providerId:'test',passkeys:{origin}} as AppConfig,{accountApi:{accounts:{authenticate:async()=>authenticated?session:null} as unknown as AccountApiRepository,grants:{} as GrantRepository,service:{} as GrantService,messaging:{drafts:{read,mutate}} as unknown as AccountMessaging},async checkReadiness(){return {ready:true};}});
  const path='/api/v1/account/drafts/019a0000-0000-7000-8000-000000000001/save',headers={Cookie:'hail_session=fixture',Origin:origin,'Content-Type':'application/json'};
  const post=(extra={},body='{}')=>app.request(path,{method:'POST',headers:{...headers,...extra},body});
  authenticated=false;expect((await post()).status).toBe(401);authenticated=true;
  expect((await post({Origin:'https://evil.example'})).status).toBe(403);
  session.scopes=['messages:read'];expect((await post()).status).toBe(403);
  session.scopes=['messages:write'];session.passkey_credential_id=null;expect((await post()).status).toBe(403);session.passkey_credential_id='key';
  session.migration_state='exporting';expect((await post()).status).toBe(409);session.migration_state=null;
  expect((await post({'Content-Type':'text/plain'})).status).toBe(415);
  expect((await post({},'{"revision":0,"revision":1}')).status).toBe(400);
  expect((await post({},' '.repeat(400001))).status).toBe(413);
  expect(mutate).not.toHaveBeenCalled();expect((await post()).status).toBe(200);
  expect(mutate).toHaveBeenCalledWith(session,'019a0000-0000-7000-8000-000000000001','save',{});
  session.scopes=['messages:read'];
  expect((await app.request('/api/v1/account/drafts?trash=false',{headers})).status).toBe(400);
  expect((await app.request('/api/v1/account/drafts?after=a&after=b',{headers})).status).toBe(400);
  expect((await app.request(path.replace('/save',''),{headers})).status).toBe(404);
});
